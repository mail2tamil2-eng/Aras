// Builds ARAS tokens into CSS variables (prefix --aras-) and a flat JSON file.
// Run: pnpm --filter @tamilarasan/aras-tokens build
import StyleDictionary from 'style-dictionary';
import { writeFile, mkdir } from 'node:fs/promises';
import { OUTPUTS, THEMES } from './themes.config.mjs';

const toPosix = (p = '') => p.replace(/\\/g, '/');

await mkdir('dist', { recursive: true });

for (const output of OUTPUTS) {
  const sd = new StyleDictionary({
    source: output.sources,
    log: { warnings: 'disabled', verbosity: 'silent' },
    platforms: {
      css: {
        transforms: ['name/kebab'],
        prefix: 'aras',
        buildPath: 'dist/',
        files: [
          {
            destination: output.file,
            format: 'css/variables',
            filter: (token) => output.include(toPosix(token.filePath)),
            options: { selector: output.selector, outputReferences: true },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

// Flat, resolved JSON of the base light theme, for AI tools, the registry and Figma import.
const json = new StyleDictionary({
  source: THEMES['base-light'],
  log: { warnings: 'disabled', verbosity: 'silent' },
  platforms: {
    json: {
      transforms: ['name/kebab'],
      prefix: 'aras',
      buildPath: 'dist/',
      files: [{ destination: 'tokens.json', format: 'json/flat' }],
    },
  },
});
await json.buildAllPlatforms();

// One entry file that loads everything in the right cascade order.
const imports = OUTPUTS.map((o) => `@import './${o.file}';`).join('\n');
const reducedMotion = `
/* WCAG 2.3.3: respect the user's reduce-motion setting */
@media (prefers-reduced-motion: reduce) {
  :root {
    --aras-motion-duration-fast: 0ms;
    --aras-motion-duration-base: 0ms;
    --aras-motion-duration-slow: 0ms;
  }
}
`;
await writeFile('dist/index.css', `/* ARAS design tokens. Generated by build.mjs. Do not edit. */\n${imports}\n${reducedMotion}`);

console.log(`ARAS tokens built: ${OUTPUTS.length} CSS files + index.css + tokens.json`);
